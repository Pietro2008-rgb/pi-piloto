    private void atualizarPainelQuiz() {
        if (indicePergunta < perguntasMapeadas.length) {
            // Alimenta os componentes com os dados da matriz
            lblPergunta.setText(perguntasMapeadas[indicePergunta][0]);
            rbOpcaoA.setText(perguntasMapeadas[indicePergunta][1]);
            rbOpcaoB.setText(perguntasMapeadas[indicePergunta][2]);
            rbOpcaoC.setText(perguntasMapeadas[indicePergunta][3]);
            rbOpcaoD.setText(perguntasMapeadas[indicePergunta][4]);
            
            buttonGroup1.clearSelection(); 
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Você concluiu todas as perguntas deste bloco!");
            btnProxima.setEnabled(false); 
        }
    }
