    private void btnProximaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnProximaActionPerformed
String alternativaEscolhida = "";
        
        if (rbOpcaoA.isSelected()) alternativaEscolhida = "A";
        else if (rbOpcaoB.isSelected()) alternativaEscolhida = "B";
        else if (rbOpcaoC.isSelected()) alternativaEscolhida = "C";
        else if (rbOpcaoD.isSelected()) alternativaEscolhida = "D";
        
        if (alternativaEscolhida.equals("")) {
            javax.swing.JOptionPane.showMessageDialog(this, "Por favor, selecione uma das alternativas!");
            return; 
        }
        
        if (alternativaEscolhida.equals(perguntasMapeadas[indicePergunta][5])) {
            quantidadeAcertos++;
        } else {
            quantidadeErros++;
        }
        
        indicePergunta++;
        atualizarPainelQuiz();    }//GEN-LAST:event_btnProximaActionPerformed

